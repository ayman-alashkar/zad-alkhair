/* أدوات النص في الرسائل. */

const AR = "٠١٢٣٤٥٦٧٨٩";

/* الأرقام العربية الهندية */
export const ar = (value: number | string) =>
  String(value).replace(/\d/g, (digit) => AR[+digit]);

/* تهريب HTML لرسائل تيليغرام (parse_mode: HTML) */
export const esc = (value: unknown) => String(value ?? "")
  .replace(/&/g, "&amp;")
  .replace(/</g, "&lt;")
  .replace(/>/g, "&gt;");

const MONTHS = [
  "كانون الثاني", "شباط", "آذار", "نيسان", "أيار", "حزيران",
  "تموز", "آب", "أيلول", "تشرين الأول", "تشرين الثاني", "كانون الأول",
];

/* تاريخ ميلادي ثم هجري (أم القرى): «١٢ آذار، ٢٢ رمضان» */
export function fmtDate(iso: string) {
  const date = new Date(`${iso}T12:00:00Z`);
  const gregorian = `${ar(date.getUTCDate())} ${MONTHS[date.getUTCMonth()]}`;
  let hijri = "";
  try {
    hijri = date.toLocaleDateString("ar-SA-u-ca-islamic-umalqura", {
      day: "numeric",
      month: "long",
      timeZone: "UTC",
    });
  } catch {
    /* التقويم الميلادي يبقى متاحًا. */
  }
  return hijri ? `${gregorian}، ${hijri}` : gregorian;
}

